-- Watermarked PDF documents. Idempotent: safe to run more than once.
--
-- Documents live in the same Mentorship tabs as videos and follow the same rules (the tab's
-- view / upload / manage role lists, private vs published, the NDA gate). The file itself sits
-- in a PRIVATE Storage bucket that only Edge Functions (service role) can read. Nobody is ever
-- given a link to the stored original: `issue-document` stamps the viewer's name and Discord ID
-- onto every page and returns those bytes directly.
--
-- Service-role only: RLS on, all client grants revoked, no Storage policies.

create table if not exists public.documents (
  id                      uuid        primary key default gen_random_uuid(),
  tab_id                  uuid        not null references public.mentorship_tabs (id) on delete restrict,
  title                   text        not null,
  description             text,
  -- Object path inside the private bucket. Generated by the server, never taken from the client.
  storage_path            text        not null unique,
  size_bytes              bigint,
  page_count              int,
  visibility              text        not null default 'private'
                            check (visibility in ('published', 'private')),
  -- uploading -> ready (after the server has checked the stored file) or failed.
  status                  text        not null default 'uploading'
                            check (status in ('uploading', 'ready', 'failed')),
  sort_ord                int         not null default 0,
  uploaded_by_discord_id  text        not null check (uploaded_by_discord_id ~ '^[0-9]{5,32}$'),
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  deleted_at              timestamptz
);

create index if not exists documents_tab_idx
  on public.documents (tab_id, sort_ord) where deleted_at is null;

alter table public.documents enable row level security;
revoke all on public.documents from anon, authenticated;

-- Private bucket: PDFs only, 25 MB each (the stamping step holds one file in memory per view).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('mentorship-documents', 'mentorship-documents', false, 26214400, array['application/pdf'])
on conflict (id) do update
  set public = false,
      file_size_limit = 26214400,
      allowed_mime_types = array['application/pdf'];

-- Playback audit: which document a grant or denial was for (no names, as for videos).
alter table public.playback_audit add column if not exists document_id uuid;

-- Content audit: documents are a new target kind. The actions are the existing ones
-- (upload_created, visibility_changed, metadata_changed, deleted, reordered).
alter table public.content_audit drop constraint if exists content_audit_target_kind_check;
alter table public.content_audit
  add constraint content_audit_target_kind_check
  check (target_kind in ('video', 'recording', 'member', 'level', 'section', 'tab', 'document'));

alter table public.content_audit drop constraint if exists content_audit_target_check;
alter table public.content_audit
  add constraint content_audit_target_check
  check (
    (target_kind = 'member'
       and target_discord_id is not null and target_id is null
       and target_level is null and target_section is null)
    or (target_kind = 'level'
       and target_level in (1, 2, 3) and target_id is null
       and target_discord_id is null and target_section is null)
    or (target_kind = 'section'
       and target_section in ('further_studying', 'lectures', 'weekly_recaps',
                              'july_batch', 'sept_batch', 'batch_5', 'recordings',
                              'tab_managers', 'nda_settings')
       and target_id is null and target_discord_id is null and target_level is null)
    or (target_kind in ('video', 'recording', 'tab', 'document')
       and target_id is not null and target_discord_id is null
       and target_level is null and target_section is null)
  );
